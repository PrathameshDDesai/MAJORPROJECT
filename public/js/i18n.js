function getLanguage() {
    return localStorage.getItem('appLang') || 'en';
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('appLang', lang);
    applyTranslations(lang);
}

function applyTranslations(lang = getLanguage()) {
    const dict = translations[lang] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (dict[key]) {
            if (elem.tagName === 'INPUT' && elem.hasAttribute('placeholder')) {
                elem.placeholder = dict[key];
            } else if (elem.children.length === 0) {
                elem.innerText = dict[key];
            } else {
                // If element has icon children (e.g. <i>), update only text nodes
                Array.from(elem.childNodes).forEach(node => {
                    if (node.nodeType === Node.TEXT_NODE && node.textContent.trim().length > 0) {
                        node.textContent = dict[key];
                    }
                });
            }
        }
    });

    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        langSelect.value = lang;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();

    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        langSelect.value = getLanguage();
        langSelect.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
    }
});
